"""Plain-text authority memo for a human reader (lawyer, auditor). Built only from the verifier's report.

Every string that comes from the bundle is passed through safe(): control characters (newlines
included) become spaces and long values are cut, so a submitted record cannot forge memo sections.
Grant details are rendered only for grant bodies that pass the same validation the verifier uses.
"""
from __future__ import annotations

import textwrap

from .spec import validate_grant_body

CENT_CURRENCIES = {"USD", "EUR", "GBP", "CAD", "AUD", "CHF"}

NOT_ESTABLISHED = [
    "that the signed wording and the structured limits say the same thing: the verifier applies the structured limits; a person must read the wording and compare;",
    "that the grant is legally valid or enforceable anywhere, or that any person had capacity or power to give it;",
    "that a revocation had legal effect: that can depend on notice to the agent and to third parties, which no log shows;",
    "that a key belongs to the named person or organisation (only a key you pinned yourself from an outside source can support that); names in the records are claimed by whoever signed them;",
    "that anything was executed or prevented: the recorder logs requests and decisions, it does not move money or stop a tool, and 'allowed' or 'refused' is what the recorder reported;",
    "that the facts inside an action (for example that an invoice was genuine) are true;",
    "that nothing is missing from the log: a record the operator never wrote cannot be seen here;",
    "how any court or regulator would treat the records, including under electronic-signature law, which differs by jurisdiction.",
]

# Display wording for verdict codes: these are format and rule checks, not legal conclusions.
VERDICT_TEXT = {
    "GRANT_OK": "grant recorded; signature and format checks pass",
    "GRANT_DEFECTIVE": "grant recorded but defective; it gives no authority in this check",
    "IN_AUTHORITY": "within the structured limits",
    "OUT_OF_AUTHORITY": "outside the structured limits",
    "REVOCATION_EFFECTIVE": "revocation recorded; signature valid",
    "REVOCATION_INEFFECTIVE": "revocation recorded but not valid in this check",
    "MALFORMED": "malformed record",
}


def safe(x, limit: int = 300) -> str:
    """Text safe to print: control characters become spaces, long values are cut."""
    s = str(x)
    s = "".join(" " if (ord(c) < 32 or ord(c) == 127) else c for c in s)
    return s if len(s) <= limit else s[:limit] + "..."


def money(amount, currency):
    if isinstance(amount, bool) or not isinstance(amount, int):
        return safe(amount)
    sign, a = ("-" if amount < 0 else ""), abs(amount)
    if currency in CENT_CURRENCIES:
        return f"{sign}{currency} {a // 100:,}.{a % 100:02d}"
    return f"{sign}{a:,} {safe(currency)}" if currency else f"{sign}{a:,}"


def _perm_line(p: dict) -> str:
    bits = [safe(p["action"])]
    cur = p.get("currency")
    if "max_amount" in p:
        bits.append(f"up to {money(p['max_amount'], cur)} each")
    if "max_total" in p:
        bits.append(f"{money(p['max_total'], cur)} in total")
    if "max_uses" in p:
        bits.append(f"at most {safe(p['max_uses'])} uses")
    if "counterparties" in p:
        bits.append("only with: " + ", ".join(safe(c, 80) for c in p["counterparties"]))
    return "; ".join(bits)


def _wrap(prefix: str, text: str) -> list:
    return textwrap.wrap(safe(text, 20000), width=96, initial_indent=prefix, subsequent_indent=prefix)


def render(rep: dict, bundle=None) -> str:
    try:
        return _render(rep, bundle)
    except Exception as ex:  # never let a hostile record make the memo unusable
        return (f"AUTHORITY MEMO\nResult: {safe(rep.get('status') if isinstance(rep, dict) else '?')}\n"
                f"The memo could not be rendered in full ({type(ex).__name__}). Use `verify --json` for the raw report.\n")


def _render(rep: dict, bundle=None) -> str:
    L = []
    add = L.append
    s = rep.get("summary") or {}
    add("AUTHORITY MEMO (generated by the authority-trail verifier)")
    add("=" * 62)
    add(f"Result: {safe(rep.get('status'))}")
    add("")
    add("1. The log")
    add(f"   Entries: {rep.get('entries', 0)}.  Hash chain: " + ("intact." if rep.get("chain", {}).get("ok") else "BROKEN or unreadable."))
    for p in rep.get("chain", {}).get("problems", []):
        where = f"entry {p['seq']}" if p["seq"] is not None else "bundle"
        add(f"   !! {safe(p['code'])} at {where}" + (f" ({safe(p['detail'])})" if p["detail"] else ""))
    ck = rep.get("checkpoint")
    if ck:
        add(f"   Your saved head (entry {safe(ck['seq'])}): " + ("found in this log." if ck["matches"] else "NOT found in this log."))
    if rep.get("anchors"):
        for a in rep["anchors"]:
            add(f"   Anchor ({safe(a['method'])}, entry {safe(a['seq'])}): {safe(a['status'])}. {safe(a['detail'], 600)}")
        if rep.get("verified_anchor_seq") is None:
            add("   No anchor was confirmed against an outside ledger in this check, so none counts as coverage.")
        else:
            add(f"   Entries after the last confirmed anchor (not covered by it): {rep['unanchored_entries']}.")
    else:
        add("   Anchors: none. Without an outside timestamp or a head you saved earlier, whoever holds the log could have rebuilt it.")
    add("")
    add("2. Who delegated to whom (names are as claimed in the records)")
    if not rep.get("roots"):
        add("   (no root grant found)")
    for r in rep.get("roots", []):
        pin = {"PINNED": "key matches a key you pinned", "NOT_PINNED": "key does NOT match any key you pinned",
               "NOT_CHECKED": "key NOT checked against any outside source"}[r["pinned"]]
        add(f"   Root: {safe(r['grantor'], 120)} (key {safe(r['key_id'])}) -> {safe(r['grantee'], 120)}   [{pin}]")
    for r in rep.get("results", []):
        if r["kind"] != "grant":
            continue
        b = r["body"]
        add("")
        add(f"   Grant {safe(r.get('id'))} [{safe((r.get('ref') or '?')[:8])}]  (entry {r['seq']}, recorded {safe(r['recorded_at'])})")
        add(f"     Check result: {VERDICT_TEXT.get(r['verdict'], safe(r['verdict']))}  [{safe(r['verdict'])}]")
        if validate_grant_body(b) == []:
            add(f"     From (name claimed in the record): {safe(b['grantor']['name'], 120)}  To: {safe(b['grantee']['name'], 120)}"
                + (f"  (sub-grant of [{safe(str(b['parent'])[:8])}])" if b.get("parent") else ""))
            add(f"     Window: {safe(b['not_before'])} to {safe(b['expires_at'])} (end excluded)")
            add(f"     Purpose: {safe(b['purpose'], 400)}")
            add(f"     Signed wording, in full (title: \"{safe(b['instrument']['title'], 200)}\"):")
            for line in _wrap("       | ", b["instrument"]["text"]):
                add(line)
            add(f"     SHA-256 of that wording: {safe(b['instrument']['text_sha256'])}")
            add("     Structured limits the verifier applies (compare them with the wording above):")
            for p in b["permissions"]:
                add("       - " + _perm_line(p))
            d = b["delegation"]
            add("     May sub-delegate: " + (f"yes, to depth {d['max_depth']}" if d["allowed"] else "no"))
        else:
            add("     (details not shown: the record does not have the required shape)")
        for x in r["reasons"]:
            add(f"     problem: {safe(x)}")
    revs = [r for r in rep.get("results", []) if r["kind"] == "revocation"]
    if revs:
        add("")
        add("3. Revocations")
        for r in revs:
            b = r["body"] if isinstance(r["body"], dict) else {}
            add(f"   Entry {r['seq']}: {safe(b.get('id'))} refers to [{safe(str(b.get('grant'))[:8])}]  "
                f"{VERDICT_TEXT.get(r['verdict'], safe(r['verdict']))}  reason given: {safe(b.get('reason'), 300)}")
            for x in r["reasons"]:
                add(f"     problem: {safe(x)}")
    add("")
    add("4. Requested actions, in log order")
    acts = [r for r in rep.get("results", []) if r["kind"] == "action"]
    if not acts:
        add("   (none)")
    for r in acts:
        b = r["body"] if isinstance(r["body"], dict) else {}
        p = b.get("params") if isinstance(b.get("params"), dict) else {}
        what = safe(b.get("action", "?"), 80)
        if "amount" in p:
            what += " " + money(p["amount"], p.get("currency"))
        if "counterparty" in p:
            what += " -> " + safe(p["counterparty"], 120)
        if r["verdict"] == "IN_AUTHORITY":
            tag = "WITHIN the structured limits; recorder reported ALLOWED" if r["gate"] == "ALLOWED" else f"WITHIN the structured limits; recorder decision: {safe(r['gate'])}"
        elif r["gate"] == "BLOCKED":
            tag = "OUTSIDE the limits; recorder reported BLOCKED (the request is on record)"
        else:
            tag = "OUTSIDE the limits BUT recorder reported it as allowed or gave no refusal"
        add(f"   #{r['seq']:<3} {safe(b.get('id'), 80)}  {what}")
        add(f"        grant [{safe(str(b.get('grant'))[:8])}], recorded {safe(r['recorded_at'])}: {tag}")
        for x in r["reasons"]:
            add(f"        - {safe(x)}")
        for x in r["warnings"]:
            add(f"        ~ {safe(x)}")
    add("")
    add(f"   Totals: {s.get('actions', 0)} requested actions: {s.get('in_authority', 0)} within limits, "
        f"{s.get('blocked_as_expected', 0)} outside limits and refused, "
        f"{s.get('allowed_outside_authority', 0)} outside limits but not refused.")
    if rep.get("budget_caveat"):
        add("   Note: limits on totals and counts count requests judged within limits, not money moved. Because at least one")
        add("   out-of-limits request was not refused, later 'within limits' verdicts that depend on those totals are conditional.")
    add("")
    add("5. Findings")
    notable = [f for f in rep.get("findings", []) if f["severity"] != "INFO"]
    if not notable:
        add("   None above informational.")
    for f in rep.get("findings", []):
        where = f"entry {f['seq']}" if f["seq"] is not None else "bundle"
        add(f"   [{safe(f['severity'])}] {safe(f['code'])} at {where}: {safe(f['detail'], 600)}")
    add("")
    add("6. What this memo does not establish")
    for x in NOT_ESTABLISHED:
        add("   - " + x)
    add("   The labels above are format and rule checks, not legal conclusions. The memo shows what was signed, in what")
    add("   order the recorder logged it, and whether each requested action is within the structured limits of the grant")
    add("   it names.")
    return "\n".join(L) + "\n"
